"use client";

import { AddressBook, ArrowUpRight, ChartBar, ListChecks, Plus, UsersThree } from "@phosphor-icons/react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import { useEffect, useState } from "react";
import { LogoMark } from "./logo";
import { buttonClass } from "./ui";

const LINKS = [
  { href: "/dashboard", label: "Dashboard", Icon: ChartBar },
  { href: "/voters", label: "Voters", Icon: AddressBook },
  { href: "/lists", label: "Lists", Icon: ListChecks },
  { href: "/volunteers", label: "Volunteers", Icon: UsersThree },
] as const;

const isActive = (pathname: string | null, href: string) =>
  pathname !== null && (pathname === href || pathname.startsWith(`${href}/`));

/** The current URL is only known at request time, so the app layout wraps this in <Suspense>. */
export function NavLinks() {
  return <AppNavigation pathname={usePathname()} />;
}

/**
 * Desktop: a sidebar with the current page highlighted. Phones: a top bar whose menu opens
 * as a full height panel. pathname null = nothing highlighted (the Suspense fallback).
 */
export function AppNavigation({ pathname }: { pathname: string | null }) {
  const [open, setOpen] = useState(false);

  useEffect(() => {
    if (!open) return;
    const onKey = (event: KeyboardEvent) => event.key === "Escape" && setOpen(false);
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [open]);

  return (
    <>
      <aside className="sticky top-0 hidden h-screen w-60 shrink-0 flex-col px-3 py-4 lg:flex">
        <Link href="/dashboard" className="mb-6 flex items-center gap-2 rounded-lg px-2 py-1 transition hover:bg-hover">
          <LogoMark />
          <span className="title-3 tracking-tight">Doorstep</span>
        </Link>
        <Link href="/lists/new" className={`${buttonClass} mb-6 w-full`}>
          <Plus size={16} weight="bold" aria-hidden />
          New list
        </Link>
        <nav aria-label="Main" className="grid gap-1">
          {LINKS.map(({ href, label, Icon }) => {
            const active = isActive(pathname, href);
            return (
              <Link
                key={href}
                href={href}
                aria-current={active ? "page" : undefined}
                className={`flex items-center gap-3 rounded-lg px-3 py-2 title-4 transition ${
                  active ? "bg-surface text-ink shadow-sm ring-1 ring-line" : "text-muted hover:bg-hover hover:text-ink"
                }`}
              >
                <Icon size={18} weight={active ? "fill" : "regular"} className={active ? "text-accent" : ""} aria-hidden />
                {label}
              </Link>
            );
          })}
        </nav>
        <div className="mt-auto rounded-xl border border-line bg-surface p-4">
          <p className="caption-3">Demo workspace</p>
          <p className="mt-1 caption-5 text-muted">Every voter is generated by a script. The data resets every night.</p>
          <Link href="/" className="mt-3 inline-flex items-center gap-1 caption-4 text-accent-ink hover:underline">
            About this demo
            <ArrowUpRight size={12} aria-hidden />
          </Link>
        </div>
      </aside>

      <div className="sticky top-0 z-40 flex items-center justify-between bg-page/80 px-4 py-3 backdrop-blur-md lg:hidden">
        <Link href="/dashboard" className="flex items-center gap-2">
          <LogoMark />
          <span className="title-3 tracking-tight">Doorstep</span>
        </Link>
        <button
          type="button"
          aria-label={open ? "Close menu" : "Open menu"}
          aria-expanded={open}
          aria-controls="mobile-menu"
          onClick={() => setOpen(!open)}
          className="relative z-50 flex size-10 items-center justify-center rounded-lg transition hover:bg-hover"
        >
          {/* Two lines that rotate into an X. */}
          <span
            aria-hidden
            className={`absolute h-0.5 w-4 rounded-full bg-ink transition-transform duration-500 motion-reduce:transition-none ${open ? "rotate-45" : "-translate-y-1"}`}
          />
          <span
            aria-hidden
            className={`absolute h-0.5 w-4 rounded-full bg-ink transition-transform duration-500 motion-reduce:transition-none ${open ? "-rotate-45" : "translate-y-1"}`}
          />
        </button>
      </div>

      <div id="mobile-menu" hidden={!open} className="fixed inset-0 z-30 bg-page/95 px-4 pt-20 backdrop-blur-xl lg:hidden">
        <nav aria-label="Mobile">
          <ul className="grid gap-2">
            {LINKS.map(({ href, label, Icon }, index) => (
              <li
                key={href}
                // Links arrive one after another: 60ms apart, the whole sequence under 400ms.
                style={{ animationDelay: `${Math.min(index * 60, 340)}ms` }}
                className="motion-safe:animate-menu-in"
              >
                <Link
                  href={href}
                  onClick={() => setOpen(false)}
                  aria-current={isActive(pathname, href) ? "page" : undefined}
                  className={`flex items-center gap-4 rounded-xl px-4 py-4 heading-6 transition ${
                    isActive(pathname, href) ? "bg-surface ring-1 ring-line" : "hover:bg-hover"
                  }`}
                >
                  <Icon size={22} className={isActive(pathname, href) ? "text-accent" : "text-muted"} aria-hidden />
                  {label}
                </Link>
              </li>
            ))}
          </ul>
          <Link
            href="/lists/new"
            onClick={() => setOpen(false)}
            className={`${buttonClass} mt-6 w-full motion-safe:animate-menu-in`}
            style={{ animationDelay: "300ms" }}
          >
            <Plus size={16} weight="bold" aria-hidden />
            New list
          </Link>
        </nav>
      </div>
    </>
  );
}
